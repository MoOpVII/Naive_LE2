CREATE PROCEDURE [dbo].[spSuppliers_Retire]
	@Id int
AS
BEGIN
	SET NOCOUNT ON;
	SET XACT_ABORT ON;
	BEGIN TRY
		BEGIN TRANSACTION;
		IF NOT EXISTS (SELECT 1 FROM dbo.Suppliers WITH (UPDLOCK, HOLDLOCK) WHERE [Id] = @Id)
			THROW 51030, 'Supplier not found.', 1;
		UPDATE dbo.Suppliers SET [IsActive] = 0 WHERE [Id] = @Id;
		COMMIT TRANSACTION;
	END TRY
	BEGIN CATCH
		IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
		THROW;
	END CATCH
END